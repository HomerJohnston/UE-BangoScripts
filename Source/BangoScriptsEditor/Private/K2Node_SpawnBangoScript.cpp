const FName UK2Node_SpawnBangoScript::ScriptPinName(TEXT("Script"));
const FName UK2Node_SpawnBangoScript::HandlePinName(TEXT("Handle"));

bool UK2Node_SpawnBangoScript::LoadParams(TArray<FBangoScriptParamInfo>& OutParams, FString& OutError) const
{
	if (ScriptPath.TrimStartAndEnd().IsEmpty())
	{
		OutError = TEXT("Type the script's path on the node, like Quest/Intro.");
		return false;
	}
	return FBangoModule::Get().GetScriptParams(ScriptPath, OutParams, OutError);
}

bool UK2Node_SpawnBangoScript::IsParamPin(const UEdGraphPin* Pin) const
{
	return Pin && Pin->Direction == EGPD_Input
		&& Pin->PinName != UEdGraphSchema_K2::PN_Execute
		&& Pin->PinName != ScriptPinName;
}

void UK2Node_SpawnBangoScript::AllocateDefaultPins()
{
	Super::AllocateDefaultPins();

	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* ScriptPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_String, ScriptPinName);
	ScriptPin->DefaultValue = ScriptPath;
	ScriptPin->PinToolTip = TEXT("The script to spawn: its path under Content/Bango without the extension, like Quest/Intro. Must be typed here, not connected.");

	UEdGraphPin* HandlePin = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Struct, FBangoScriptHandle::StaticStruct(), HandlePinName);
	HandlePin->PinToolTip = TEXT("The spawned script, for Terminate Bango Script and Is Bango Script Running. Invalid if the script couldn't start.");

	CreateParamPins();
}

void UK2Node_SpawnBangoScript::CreateParamPins()
{
	ParamDefaults.Reset();
	LoadError.Reset();

	if (ScriptPath.TrimStartAndEnd().IsEmpty())
	{
		UpdateErrorDisplay();
		return;
	}

	TArray<FBangoScriptParamInfo> Params;
	if (!LoadParams(Params, LoadError))
	{
		UpdateErrorDisplay();
		return;
	}

	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	for (const FBangoScriptParamInfo& Param : Params)
	{
		FEdGraphPinType PinType;
		FString TypeError;
		if (!BangoPinUtils::MakePinType(Param.Type, PinType, TypeError))
		{
			if (LoadError.IsEmpty())
			{
				LoadError = FString::Printf(TEXT("Parameter '%s': %s"), *Param.Name, *TypeError);
			}
			continue;
		}

		UEdGraphPin* Pin = CreatePin(EGPD_Input, PinType, FName(*Param.Name));
		Pin->PinFriendlyName = FText::FromString(BangoPinUtils::PinLabel(Param.Name));

		const FString DefaultText = BangoPinUtils::DefaultValueText(Param);
		if (Param.bHasDefault)
		{
			Pin->DefaultValue = DefaultText;
			Pin->AutogeneratedDefaultValue = DefaultText;
			Pin->PinToolTip = FString::Printf(TEXT("%s %s = %s (optional: leave unconnected and unchanged to use the script's default)"),
				*Param.Type.ToString(), *Param.Name, *Param.Default.ToDebugString());
		}
		else
		{
			Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
			Pin->PinToolTip = FString::Printf(TEXT("%s %s (required)"), *Param.Type.ToString(), *Param.Name);
		}
		ParamDefaults.Add(Pin->PinName, Pin->DefaultValue);
	}
	UpdateErrorDisplay();
}

void UK2Node_SpawnBangoScript::UpdateErrorDisplay()
{
	bHasCompilerMessage = !LoadError.IsEmpty();
	ErrorType = EMessageSeverity::Error;
	ErrorMsg = LoadError;
}

void UK2Node_SpawnBangoScript::RefreshParamPins()
{
	TArray<UEdGraphPin*> OldParamPins;
	for (int32 i = Pins.Num() - 1; i >= 0; --i)
	{
		if (IsParamPin(Pins[i]))
		{
			OldParamPins.Add(Pins[i]);
			Pins.RemoveAt(i);
		}
	}

	PreviousParamDefaults = ParamDefaults;
	CreateParamPins();
	RewireOldPinsToNewPins(OldParamPins, Pins, nullptr);
	ApplyChangedDefaults();

	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyGraphChanged();
	}
	if (UBlueprint* Blueprint = GetBlueprint())
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

void UK2Node_SpawnBangoScript::ApplyChangedDefaults()
{
	for (UEdGraphPin* Pin : Pins)
	{
		if (!IsParamPin(Pin) || Pin->LinkedTo.Num() > 0)
		{
			continue;
		}
		const FString* Previous = PreviousParamDefaults.Find(Pin->PinName);
		const FString* Current = ParamDefaults.Find(Pin->PinName);
		if (Previous && Current && *Previous != *Current && Pin->DefaultValue == *Previous)
		{
			// The designer never changed this pin, so it follows the script's new default.
			Pin->DefaultValue = *Current;
		}
	}
	PreviousParamDefaults.Reset();
}

void UK2Node_SpawnBangoScript::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	PreviousParamDefaults = ParamDefaults;
	Super::ReallocatePinsDuringReconstruction(OldPins);
}

void UK2Node_SpawnBangoScript::PostReconstructNode()
{
	Super::PostReconstructNode();
	ApplyChangedDefaults();
}

void UK2Node_SpawnBangoScript::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (Pin && Pin->PinName == ScriptPinName && Pin->DefaultValue != ScriptPath)
	{
		ScriptPath = Pin->DefaultValue;
		RefreshParamPins();
	}
}

FText UK2Node_SpawnBangoScript::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	const FText BaseTitle = LOCTEXT("Title", "Spawn Bango Script");
	if (TitleType == ENodeTitleType::MenuTitle || TitleType == ENodeTitleType::ListView || ScriptPath.TrimStartAndEnd().IsEmpty())
	{
		return BaseTitle;
	}
	return FText::Format(LOCTEXT("TitleWithPath", "Spawn Bango Script\n{0}"), FText::FromString(ScriptPath));
}

FText UK2Node_SpawnBangoScript::GetTooltipText() const
{
	return LOCTEXT("Tooltip",
		"Starts a Bango script. Type its path on the node (like Quest/Intro) to get a pin for each of the script's parameters.\n"
		"Optional parameters use the script's default while their pin is unconnected and unchanged.\n"
		"If the script's parameters change, right-click the node and choose Refresh Node.");
}

FText UK2Node_SpawnBangoScript::GetMenuCategory() const
{
	return LOCTEXT("Category", "Bango");
}

void UK2Node_SpawnBangoScript::GetMenuActions(FBlueprintActionDatabaseRegistrar& ActionRegistrar) const
{
	UClass* ActionKey = GetClass();
	if (ActionRegistrar.IsOpenForRegistration(ActionKey))
	{
		UBlueprintNodeSpawner* Spawner = UBlueprintNodeSpawner::Create(GetClass());
		check(Spawner);
		ActionRegistrar.AddBlueprintAction(ActionKey, Spawner);
	}
}

void UK2Node_SpawnBangoScript::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	const UEdGraphPin* ScriptPin = FindPin(ScriptPinName);
	if (ScriptPin && ScriptPin->LinkedTo.Num() > 0)
	{
		MessageLog.Error(*LOCTEXT("ScriptPinLinked", "@@: the script path must be typed on the node, not connected. To choose a script at runtime, use Spawn Bango Script (Dynamic Path).").ToString(), this);
	}
}

void UK2Node_SpawnBangoScript::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);
	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();

	auto Fail = [&](const FString& Message)
	{
		CompilerContext.MessageLog.Error(*FString::Printf(TEXT("@@: %s"), *Message), this);
		BreakAllNodeLinks();
	};

	const UEdGraphPin* ScriptPin = FindPin(ScriptPinName);
	if (ScriptPin && ScriptPin->LinkedTo.Num() > 0)
	{
		BreakAllNodeLinks();
		return; // already reported by ValidateNodeDuringCompilation
	}

	TArray<FBangoScriptParamInfo> Params;
	FString Error;
	if (!LoadParams(Params, Error))
	{
		Fail(Error);
		return;
	}

	// The pins must still match the script's parameters.
	TArray<UEdGraphPin*> ParamPins;
	for (const FBangoScriptParamInfo& Param : Params)
	{
		FEdGraphPinType Expected;
		if (!BangoPinUtils::MakePinType(Param.Type, Expected, Error))
		{
			Fail(FString::Printf(TEXT("Parameter '%s': %s"), *Param.Name, *Error));
			return;
		}
		UEdGraphPin* Pin = FindPin(FName(*Param.Name), EGPD_Input);
		if (!Pin || !BangoPinUtils::PinTypesMatch(Pin->PinType, Expected))
		{
			Fail(FString::Printf(TEXT("The parameters of '%s' have changed since this node was refreshed. Right-click the node and choose Refresh Node."), *ScriptPath));
			return;
		}
		ParamPins.Add(Pin);
	}

	auto SpawnLibraryCall = [&](FName FunctionName) -> UK2Node_CallFunction*
	{
		UK2Node_CallFunction* Call = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Call->FunctionReference.SetExternalMember(FunctionName, UBangoBlueprintLibrary::StaticClass());
		Call->AllocateDefaultPins();
		return Call;
	};

	// MakeBangoArgs -> AddBangoArg... / SkipBangoArg for each parameter -> SpawnBangoScriptWithArgs
	UK2Node_CallFunction* MakeNode = SpawnLibraryCall(GET_FUNCTION_NAME_CHECKED(UBangoBlueprintLibrary, MakeBangoArgs));
	UEdGraphPin* ArgsPin = MakeNode->GetReturnValuePin();

	for (int32 i = 0; i < Params.Num(); ++i)
	{
		const FBangoScriptParamInfo& Param = Params[i];
		UEdGraphPin* Pin = ParamPins[i];
		const bool bTextPin = Param.Type.Base == EBangoBaseType::Text && !Param.Type.IsArray();
		const bool bNotPassed = Pin->LinkedTo.Num() == 0
			&& BangoPinUtils::IsUnchangedDefault(Param, bTextPin ? Pin->DefaultTextValue.ToString() : Pin->DefaultValue);

		UK2Node_CallFunction* AddNode = SpawnLibraryCall(bNotPassed
			? GET_FUNCTION_NAME_CHECKED(UBangoBlueprintLibrary, SkipBangoArg)
			: BangoPinUtils::GetAddFunctionName(Param.Type));
		Schema->TryCreateConnection(ArgsPin, AddNode->FindPinChecked(TEXT("Args")));

		if (!bNotPassed)
		{
			UEdGraphPin* ValuePin = AddNode->FindPinChecked(TEXT("Value"));
			if (Pin->LinkedTo.Num() > 0)
			{
				CompilerContext.MovePinLinksToIntermediate(*Pin, *ValuePin);
			}
			else
			{
				ValuePin->DefaultValue = Pin->DefaultValue;
				ValuePin->DefaultObject = Pin->DefaultObject;
				ValuePin->DefaultTextValue = Pin->DefaultTextValue;
			}
		}
		ArgsPin = AddNode->GetReturnValuePin();
	}

	UK2Node_CallFunction* SpawnNode = SpawnLibraryCall(GET_FUNCTION_NAME_CHECKED(UBangoBlueprintLibrary, SpawnBangoScriptWithArgs));
	SpawnNode->FindPinChecked(TEXT("ScriptPath"))->DefaultValue = ScriptPath;
	Schema->TryCreateConnection(ArgsPin, SpawnNode->FindPinChecked(TEXT("Args")));

	UK2Node_Self* SelfNode = CompilerContext.SpawnIntermediateNode<UK2Node_Self>(this, SourceGraph);
	SelfNode->AllocateDefaultPins();
	Schema->TryCreateConnection(SelfNode->FindPinChecked(UEdGraphSchema_K2::PN_Self), SpawnNode->FindPinChecked(TEXT("WorldContextObject")));

	CompilerContext.MovePinLinksToIntermediate(*GetExecPin(), *SpawnNode->GetExecPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(UEdGraphSchema_K2::PN_Then), *SpawnNode->GetThenPin());
	CompilerContext.MovePinLinksToIntermediate(*FindPinChecked(HandlePinName), *SpawnNode->GetReturnValuePin());

	BreakAllNodeLinks();
}

